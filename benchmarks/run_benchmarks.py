"""Runtime and peak-memory scaling benchmarks for MSATK.

Each configuration runs in a fresh subprocess so that peak resident memory
(``ru_maxrss``) is measured per run. Synthetic alignments are generated by
mutating a random ancestor (DNA) with a fixed seed, so results are reproducible.

Usage::

    python benchmarks/run_benchmarks.py --sizes 100,1000,5000 --lengths 1000,10000 \
        --modes stats_none,stats_auto,profile_basic --out benchmarks/results.csv

Modes
-----
stats_none      statistics with pairwise comparison disabled
stats_auto      statistics with the default size-aware pairwise policy
stats_exact     statistics with exact all-vs-all pairwise identity
profile_basic   full ``msatk profile --preset basic`` (tables + report, no figures)
"""

from __future__ import annotations

import argparse
import csv
import json
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

WORKER = r"""
import json, resource, sys, time
from pathlib import Path
mode, path, out = sys.argv[1], sys.argv[2], sys.argv[3]
t0 = time.perf_counter()
from msatk import MSATK
if mode.startswith("stats_"):
    p = MSATK(path, sequence_type="dna", pairwise=mode.split("_", 1)[1])
    s = p.stats().summary
    n_metrics = len(s) + len(p.stats().sites[0]) + len(p.stats().sequences[0])
else:
    p = MSATK(path, sequence_type="dna")
    r = p.write_outputs(out, plots=False, preset="basic", force=True)
    s = r["summary"]
    n_metrics = len(s)
elapsed = time.perf_counter() - t0
rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
rss_mb = rss / (1024 * 1024) if sys.platform == "darwin" else rss / 1024
out_bytes = sum(f.stat().st_size for f in Path(out).rglob("*") if f.is_file()) if Path(out).exists() else 0
print(json.dumps({"seconds": elapsed, "peak_rss_mb": rss_mb, "pairwise_method": s.get("pairwise_method"),
                  "fields": n_metrics, "output_bytes": out_bytes}))
"""


def synthetic_fasta(path: Path, n: int, length: int, seed: int = 1) -> None:
    import numpy as np

    rng = np.random.default_rng(seed)
    anc = rng.integers(0, 4, length)
    alphabet = np.frombuffer(b"ACGT-", dtype=np.uint8)
    with path.open("w") as handle:
        for i in range(n):
            row = anc.copy()
            mutate = rng.random(length) < 0.05
            row[mutate] = rng.integers(0, 4, mutate.sum())
            if i % 10 == 0:  # some gapped fragments
                start = rng.integers(0, length // 2)
                row[start : start + length // 20] = 4
            handle.write(f">seq{i}\n{alphabet[row].tobytes().decode()}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sizes", default="100,1000,5000")
    ap.add_argument("--lengths", default="1000,10000")
    ap.add_argument("--modes", default="stats_none,stats_auto,profile_basic")
    ap.add_argument("--max-cells", type=float, default=6e7, help="Skip configurations above N*L.")
    ap.add_argument("--out", default="benchmarks/results.csv")
    args = ap.parse_args()
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for n in map(int, args.sizes.split(",")):
            for length in map(int, args.lengths.split(",")):
                if n * length > args.max_cells:
                    continue
                fasta = Path(tmp) / f"syn_{n}x{length}.fasta"
                synthetic_fasta(fasta, n, length)
                for mode in args.modes.split(","):
                    outdir = Path(tmp) / f"out_{n}_{length}_{mode}"
                    proc = subprocess.run(
                        [sys.executable, "-c", WORKER, mode, str(fasta), str(outdir)],
                        capture_output=True,
                        text=True,
                    )
                    if proc.returncode != 0:
                        print(proc.stderr, file=sys.stderr)
                        continue
                    result = json.loads(proc.stdout.strip().splitlines()[-1])
                    row = {"sequences": n, "sites": length, "cells": n * length, "mode": mode, **result}
                    rows.append(row)
                    print(
                        f"{n:>6} x {length:>6}  {mode:<14} {result['seconds']:8.2f} s "
                        f"{result['peak_rss_mb']:8.1f} MB  pairwise={result['pairwise_method']}"
                    )
    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    meta = {"python": sys.version.split()[0], "platform": platform.platform(), "processor": platform.processor()}
    target.with_suffix(".json").write_text(json.dumps({"environment": meta, "results": rows}, indent=2))
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
