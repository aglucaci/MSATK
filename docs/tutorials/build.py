"""Build the tutorials: run every code block and insert its real output.

Templates live in ``docs/tutorials/_src/*.md``. Each template is executed top to
bottom in a fresh working directory:

* ```` ```python ```` blocks run in one namespace per tutorial; printed output is
  inserted below the block.
* ```` ```bash ```` blocks: each line starting with ``msatk`` runs through the CLI;
  output is inserted below the block (other lines are shown but not run).
* ``<!-- figure: path/in/workdir.png | alt text -->`` copies a generated figure to
  ``docs/tutorials/img/`` and embeds it.
* ``<!-- hide-output -->`` immediately before a block suppresses its output.

Usage::

    python docs/tutorials/build.py            # rebuild docs/tutorials/*.md
    python docs/tutorials/build.py --check    # run everything, write nothing
"""

from __future__ import annotations

import argparse
import contextlib
import io
import os
import re
import shlex
import shutil
import sys
import tempfile
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

HERE = Path(__file__).resolve().parent
SRC = HERE / "_src"
IMG = HERE / "img"
FENCE = re.compile(r"^```(\w*)\s*$")
FIGURE = re.compile(r"^<!--\s*figure:\s*(\S+)\s*(?:\|\s*(.*?))?\s*-->\s*$")
MAX_LINES = 40


def _truncate(text: str) -> str:
    lines = text.rstrip("\n").splitlines()
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES] + [f"... ({len(lines) - MAX_LINES} more lines)"]
    return "\n".join(line.rstrip() for line in lines)


def _run_python(code: str, ns: dict[str, object]) -> str:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        exec(compile(code, "<tutorial>", "exec"), ns)  # noqa: S102 - trusted local templates
    return buf.getvalue()


def _run_bash(code: str) -> str:
    from msatk.cli import main

    out = io.StringIO()
    for line in code.splitlines():
        line = line.strip()
        if not line.startswith("msatk "):
            continue
        argv = shlex.split(line)[1:]
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            code_ = main(argv)
        if code_ != 0:
            raise RuntimeError(f"`{line}` exited with {code_}:\n{out.getvalue()}")
    return out.getvalue()


def build_one(template: Path, write: bool) -> float:
    slug = template.stem
    text = template.read_text(encoding="utf-8")
    out_lines: list[str] = [
        f"<!-- Generated by docs/tutorials/build.py from _src/{template.name}; edit the template. -->",
        "",
    ]
    ns: dict[str, object] = {"__name__": "__tutorial__"}
    lines = text.splitlines()
    i = 0
    hide_next = False
    start = time.perf_counter()
    cwd = os.getcwd()
    work = Path(tempfile.mkdtemp(prefix=f"msatk-{slug}-"))
    os.chdir(work)
    try:
        while i < len(lines):
            line = lines[i]
            fig = FIGURE.match(line)
            if fig:
                src, alt = fig.group(1), fig.group(2) or ""
                target = IMG / f"{slug}-{Path(src).name}"
                if write:
                    IMG.mkdir(exist_ok=True)
                    shutil.copyfile(work / src, target)
                elif not (work / src).exists():
                    raise FileNotFoundError(f"{template.name}: figure {src} was not created")
                out_lines.append(f"![{alt}](img/{target.name})")
                i += 1
                continue
            if line.strip() == "<!-- hide-output -->":
                hide_next = True
                i += 1
                continue
            m = FENCE.match(line)
            if not m or not m.group(1):
                out_lines.append(line)
                i += 1
                continue
            lang = m.group(1)
            j = i + 1
            while j < len(lines) and not lines[j].startswith("```"):
                j += 1
            code = "\n".join(lines[i + 1 : j])
            out_lines += lines[i : j + 1]
            try:
                if lang == "python":
                    result = _run_python(code, ns)
                elif lang == "bash":
                    result = _run_bash(code)
                else:
                    result = ""
            except Exception as exc:
                raise RuntimeError(f"{template.name}: block at line {i + 1} failed: {exc}") from exc
            if result.strip() and not hide_next:
                out_lines += ["", "```text", _truncate(result), "```"]
            hide_next = False
            i = j + 1
    finally:
        os.chdir(cwd)
        shutil.rmtree(work, ignore_errors=True)
    if write:
        (HERE / template.name).write_text("\n".join(out_lines).rstrip() + "\n", encoding="utf-8")
    return time.perf_counter() - start


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="Run all blocks without writing files.")
    ap.add_argument("names", nargs="*", help="Template stems to build (default: all).")
    args = ap.parse_args()
    templates = sorted(SRC.glob("*.md"))
    if args.names:
        templates = [t for t in templates if t.stem in args.names]
    for t in templates:
        seconds = build_one(t, write=not args.check)
        print(f"{'checked' if args.check else 'built'} {t.name} ({seconds:.1f} s)", file=sys.stderr)


if __name__ == "__main__":
    main()
